/**
 * 分享卡片金句
 *
 * 由模型针对每幅画现写，而不是从语录库里挑现成的。
 * 理由：通用语录（"要爱自己""接纳不完美"）正是巴纳姆效应的温床，
 * 而本项目的立场是拒绝那种"读起来很准"的空话。
 *
 * 语感参考罗杰斯 / 荣格 / 温尼科特，但要求重写而非引用。
 *
 * 隐私红线：绝不能引用问卷原文。用户写的身体感受与生活处境
 * 属于极私密内容，不能出现在要发朋友圈的图片上。
 */

export const SHARE_QUOTE_SYSTEM = `你为一张要发到朋友圈的分享卡片写一句话。

这句话的作用：让刷到的人停下来，感到被说中，并产生"我也想试试"的念头。

## 硬性要求

1. **18~30 字**，一句话
2. **绝对不能引用创作者的问卷原文**。他们写下的身体感受、情绪状态、
   生活处境属于私密内容，不能出现在公开卡片上。只能写你自己的表述。
3. **不做诊断、不贴标签**。不写"你是XX型的人""你有XX倾向"。
4. **不写空泛鸡汤**。"要爱自己""一切都会好起来"这类放之四海皆准的话是失败的——
   那正是巴纳姆效应，读起来很准，其实什么也没说。
5. 必须**贴着这幅画和这份报告**写。换一幅画就不成立，才算合格。
6. 不要引号、不要句号结尾、不要任何解释。

## 语感参考

从这些心理学传统中汲取语感，但**不要直接引用**：

- 罗杰斯：奇妙的悖论是，当我接受自己本来的样子时，我才能改变。
- 荣格：往外张望的人在做梦，向内审视的人才是清醒的。
- 荣格：与其做好人，我宁愿做一个完整的人。
- 温尼科特：真我需要一个足够安全的环境才敢显现。

它们的共同点：**克制、有转折、把人往内引，而不给结论。**
常见结构是"看起来是 A，也许其实是 B"——把一个看似负面的东西
重新看见为某种力量，但不武断。

## 输出

只输出这一句话本身。`;

export function buildShareQuotePrompt({ drawingTitle, report }) {
  const dims = (report.dimensions || [])
    .map((d) => `- ${d.title}：${String(d.content).slice(0, 220)}`)
    .join('\n');

  return `作品名：《${drawingTitle || '无题'}》

整体回应：${report.summary}

观察维度：
${dims}`;
}

export { buildEvidenceBrief };
