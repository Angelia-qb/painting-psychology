/**
 * 分享卡片金句
 *
 * 关键教训：第一版要求"必须贴着这幅画写"，结果模型写出
 * 「向外炸开的那些线，也许不是在毁掉什么…」这类句子——
 * 对创作者本人成立，但朋友圈里的人没见过这幅画，读到只觉得莫名其妙。
 *
 * 正确的目标是：**从这幅画出发，写出一句不依赖这幅画也能成立的话。**
 * 画作是灵感来源，不是描述对象。
 */

export const SHARE_QUOTE_SYSTEM = `你为一张要发到朋友圈的卡片写一句话。

## 最重要的一条

读到这句话的人**没有看过这幅画**，也不认识创作者。

所以：**绝不能出现画面元素**。不许写"那些线""中心的圆""这片蓝"。
一旦提到画里的东西，别人就看不懂了。

你要做的是：从这幅画和这份分析里，提炼出**一句关于人的话**——
把它单独发出来，任何一个陌生人读到都能懂，并且可能被戳中。

## 要求

1. **12~22 字**。宁短勿长，一口气能读完。
2. **说人的处境，不说画的内容。**
3. 不做诊断、不贴标签，不写"你是XX的人"。
4. 不写万能鸡汤。"要爱自己""一切都会好起来"这种放之四海皆准的话，
   读起来很准其实什么也没说——这正是巴纳姆效应，是失败的。
5. 不要引号，不要句号结尾。
6. 句式不要总用"不是A，而是B"，换着写。

## 好句子长什么样

这些是心理学传统里真正流传开的话，注意它们的共同点——
**短、独立成立、说的是人的处境**：

- 当我接受自己本来的样子时，我才能改变（罗杰斯）
- 往外张望的人在做梦，向内审视的人才是清醒的（荣格）
- 与其做好人，我宁愿做一个完整的人（荣格）
- 你没有觉察到的事情，就会变成你的命运（荣格）

不要引用它们，但要写出这种质地：克制、有转折、把人往内引。

## 怎么从画里提炼

看这份报告在讲什么**人的状态**——是压抑后的释放？是想被看见？
是疲惫中还留着一点光？然后就那个状态写一句话，
把画面细节全部丢掉。

## 还要写一个问题

除了金句，再写**一个问题**，放在卡片下方。

同样的规则：**不能提到画**。不能写"如果这幅画继续发展下去…"，
陌生人没见过这幅画。

这个问题要能让任何人读到都愣一下、想了想自己。
**10~20 字**，问句。

参考感觉：
- 你上一次真正休息，是什么时候
- 那句你一直想听的话，是谁该说的
- 你在等的那个人，会来吗

## 输出格式

严格输出两行，不要任何其他内容：

QUOTE: <金句>
QUESTION: <问题>`;

export function buildShareQuotePrompt({ drawingTitle, report }) {
  const dims = (report.dimensions || [])
    .map((d) => `- ${d.title}：${String(d.content).slice(0, 220)}`)
    .join('\n');

  return `以下是一份绘画心理探索报告。请从中提炼一句关于人的话，
**不要提及任何画面元素**。

作品名：《${drawingTitle || '无题'}》

整体回应：${report.summary}

观察维度：
${dims}`;
}

export { buildEvidenceBrief };
